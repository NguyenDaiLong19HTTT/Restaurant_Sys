import { chromium } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
const stack = JSON.parse(readFileSync('.local/stack.json', 'utf8'));
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await page.goto(`http://127.0.0.1:${stack.webPort}/dang-nhap`);
await page.getByLabel('Tên đăng nhập').fill('owner');
await page.getByLabel('Mật khẩu', { exact: true }).fill(readFileSync('.local/demo-password', 'utf8').trim());
await page.getByRole('button', { name: 'Đăng nhập' }).click();
await page.waitForURL('**/app/mon-an');
await page.locator('#dish-rows tr').first().waitFor();
mkdirSync('docs/screenshots', { recursive: true });
await page.screenshot({ path: 'docs/screenshots/menu-desktop.png', fullPage: true });
await page.locator('#add-dish').click();
await page.getByRole('dialog').getByLabel('Tên món').fill('Món ngon cuối tuần');
await page.getByRole('dialog').getByLabel('Loại món').fill('Món chính');
await page.getByRole('dialog').getByLabel('Giá bán').fill('95000');
await page.getByRole('dialog').getByLabel('Hình ảnh').fill('/images/pho.svg');
await page.getByRole('dialog').getByAltText('Xem trước ảnh món ăn').waitFor();
await page.screenshot({ path: 'docs/screenshots/menu-form.png', fullPage: true });
await page.keyboard.press('Escape');
await page.setViewportSize({ width: 390, height: 844 });
await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
console.log(JSON.stringify(await page.evaluate(() => ({ width: innerWidth, documentWidth: document.documentElement.scrollWidth, overflows: [...document.querySelectorAll('body,body *')].filter(el => el.scrollWidth > el.clientWidth + 1 && !el.parentElement.closest('.table-scroll')).map(el => ({ tag: el.tagName, class: el.className, overflow: getComputedStyle(el).overflow, width: el.clientWidth, scroll: el.scrollWidth, right: el.getBoundingClientRect().right, text: el.textContent.slice(0, 40) })) })), null, 2));
await page.screenshot({ path: 'docs/screenshots/menu-mobile.png', fullPage: true });
await browser.close();
