CREATE TABLE IF NOT EXISTS dishes (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  code VARCHAR(45) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL,
  normalized_name VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
  category VARCHAR(100) NOT NULL,
  price_vnd BIGINT UNSIGNED NOT NULL,
  description TEXT NULL,
  image_url VARCHAR(2048) NULL,
  status ENUM('ACTIVE','DELETED') NOT NULL DEFAULT 'ACTIVE',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT positive_price CHECK (price_vnd > 0 AND price_vnd <= 999999999999),
  INDEX dishes_status_created (status, created_at)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS idempotency_keys (
  scope_key CHAR(64) CHARACTER SET ascii PRIMARY KEY,
  request_hash CHAR(64) CHARACTER SET ascii NOT NULL,
  response_json JSON NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
