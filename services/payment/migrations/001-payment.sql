CREATE TABLE IF NOT EXISTS demo_orders (
 id VARCHAR(64) PRIMARY KEY, branch_id VARCHAR(64) NOT NULL, code VARCHAR(80) NOT NULL,
 items JSON NOT NULL, version INT NOT NULL DEFAULT 1, status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
 payment_status VARCHAR(20) NOT NULL DEFAULT 'UNPAID', paid_payment_id CHAR(36) NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS vouchers (
 code VARCHAR(40) PRIMARY KEY, kind ENUM('FIXED','PERCENT') NOT NULL, value INT UNSIGNED NOT NULL,
 max_discount_vnd BIGINT UNSIGNED NOT NULL, min_total_vnd BIGINT UNSIGNED NOT NULL,
 max_uses INT UNSIGNED NOT NULL, used_count INT UNSIGNED NOT NULL DEFAULT 0,
 held_count INT UNSIGNED NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE,
 expires_at DATETIME NOT NULL, CHECK (used_count + held_count <= max_uses)
);
CREATE TABLE IF NOT EXISTS payment_orders (
 order_id VARCHAR(64) PRIMARY KEY, branch_id VARCHAR(64) NOT NULL, snapshot JSON NOT NULL,
 subtotal_vnd BIGINT UNSIGNED NOT NULL, order_version INT NOT NULL,
 active_payment_id CHAR(36) NULL, paid_payment_id CHAR(36) NULL UNIQUE, needs_review BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE TABLE IF NOT EXISTS payments (
 id CHAR(36) PRIMARY KEY, order_id VARCHAR(64) NOT NULL, branch_id VARCHAR(64) NOT NULL,
 method ENUM('CASH','VNPAY') NOT NULL,
 state ENUM('CASH_PENDING','PROVIDER_PENDING','RECEIVED','FAILED','CANCELLED','FINALIZING','COMPLETED') NOT NULL,
 subtotal_vnd BIGINT UNSIGNED NOT NULL, discount_vnd BIGINT UNSIGNED NOT NULL, total_vnd BIGINT UNSIGNED NOT NULL,
 voucher_code VARCHAR(40) NULL, txn_ref VARCHAR(40) NOT NULL UNIQUE, provider_transaction_no VARCHAR(30) NULL UNIQUE,
 provider_created_at CHAR(14) NOT NULL, expires_at CHAR(14) NOT NULL, provider_result VARCHAR(30) NULL,
 created_by VARCHAR(64) NOT NULL, confirmed_by VARCHAR(64) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), completed_at DATETIME(3) NULL,
 CHECK (total_vnd > 0 AND total_vnd = subtotal_vnd - discount_vnd),
 INDEX payment_order (order_id), INDEX payment_branch (branch_id,created_at)
);
CREATE TABLE IF NOT EXISTS payment_keys (
 scope_key CHAR(64) PRIMARY KEY, request_hash CHAR(64) NOT NULL, payment_id CHAR(36) NULL
);
CREATE TABLE IF NOT EXISTS voucher_reservations (
 payment_id CHAR(36) PRIMARY KEY, code VARCHAR(40) NOT NULL, state ENUM('HELD','USED','RELEASED') NOT NULL
);
CREATE TABLE IF NOT EXISTS voucher_uses (
 payment_id CHAR(36) PRIMARY KEY, order_id VARCHAR(64) NOT NULL UNIQUE, code VARCHAR(40) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE TABLE IF NOT EXISTS invoices (
 id CHAR(36) PRIMARY KEY, code VARCHAR(45) NOT NULL UNIQUE, payment_id CHAR(36) NOT NULL UNIQUE,
 order_id VARCHAR(64) NOT NULL UNIQUE, branch_id VARCHAR(64) NOT NULL, document JSON NOT NULL,
 total_vnd BIGINT UNSIGNED NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE TABLE IF NOT EXISTS revenue_entries (
 payment_id CHAR(36) PRIMARY KEY, order_id VARCHAR(64) NOT NULL UNIQUE,
 invoice_id CHAR(36) NOT NULL UNIQUE, branch_id VARCHAR(64) NOT NULL, amount_vnd BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE TABLE IF NOT EXISTS payment_outbox (
 payment_id CHAR(36) PRIMARY KEY, state ENUM('PENDING','DONE') NOT NULL DEFAULT 'PENDING',
 attempts INT UNSIGNED NOT NULL DEFAULT 0, next_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), last_error VARCHAR(80) NULL
);
CREATE TABLE IF NOT EXISTS provider_events (
 event_hash CHAR(64) PRIMARY KEY, payment_id CHAR(36) NOT NULL, source VARCHAR(10) NOT NULL,
 response_code VARCHAR(10) NOT NULL, transaction_status VARCHAR(10) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE TABLE IF NOT EXISTS query_requests (
 id CHAR(32) PRIMARY KEY, payment_id CHAR(36) NOT NULL, outcome VARCHAR(40) NOT NULL DEFAULT 'PENDING',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
