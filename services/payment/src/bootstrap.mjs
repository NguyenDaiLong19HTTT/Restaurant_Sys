import mysql from 'mysql2/promise';
import {secret} from '../../../packages/http.mjs';
let connection;
try{
 connection=await mysql.createConnection({host:process.env.DB_HOST,user:'root',password:secret('DB_ROOT_PASSWORD_FILE')});
 const password=secret('PAYMENT_DB_PASSWORD_FILE');
 if(!/^[a-f0-9]{64}$/.test(password))throw new Error('Payment DB password must be generated by setup-payment');
 await connection.query('CREATE DATABASE IF NOT EXISTS payment_db CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin');
 // No ALTER USER: reruns must never rotate a password attached to an existing database.
 await connection.query(`CREATE USER IF NOT EXISTS 'payment_app'@'%' IDENTIFIED BY '${password}'`);
 await connection.query("GRANT ALL PRIVILEGES ON payment_db.* TO 'payment_app'@'%'");
 console.log('payment_db bootstrap complete; menu_db untouched');
}catch(error){
 // mysql2 errors can include the SQL statement. Never log a CREATE USER statement containing its password.
 console.error(`PAYMENT_DB_BOOTSTRAP_FAILED:${error.code||'CONFIGURATION_ERROR'}`);process.exitCode=1;
}finally{if(connection)await connection.end();}
